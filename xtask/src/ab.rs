//! `cargo xtask control ab --bin <DSView>`: runs the same probes against
//! DSView once per implementation (DSVIEW_IMPL=c, then rust) and requires
//! identical answers. The binary must be built with -DDSVIEW_RUST_CORE=ON and
//! sit in an install layout (<prefix>/bin/DSView next to <prefix>/share/DSView).
//! First it checks the release R1 default: started without DSVIEW_IMPL*, every
//! subsystem runs Rust.

use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant};

use anyhow::{Context, Result, bail};
use dsview_testkit::control::Client;
use dsview_testkit::corpus::Corpus;
use serde_json::{Value, json};

struct Instance {
    child: Child,
    socket: PathBuf,
    home: PathBuf,
}

impl Drop for Instance {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
        let _ = std::fs::remove_file(&self.socket);
        let _ = std::fs::remove_dir_all(&self.home);
    }
}

/// Every subsystem `DSVIEW_IMPL_<name>` selects (controlapi.cpp `version`).
const SUBSYSTEMS: [&str; 8] = [
    "FORMATS",
    "STORE",
    "DECODE",
    "DRV_DEMO",
    "DRV_FILE",
    "DRV_DSLOGIC",
    "DRV_DSCOPE",
    "ACQ",
];

/// Starts DSView headless with an isolated profile (first-run dialogs off),
/// with `DSVIEW_IMPL=iml`, or with no DSVIEW_IMPL* at all for `None`, where
/// every subsystem must run Rust (the R1 default).
fn launch(bin: &Path, iml: Option<&str>) -> Result<Instance> {
    let expect = iml.unwrap_or("rust");
    let tag = format!("{}-{}", std::process::id(), iml.unwrap_or("default"));
    let home = std::env::temp_dir().join(format!("dsview-ab-home-{tag}"));
    let conf = home.join(".config/DreamSourceLab");
    std::fs::create_dir_all(&conf)?;
    std::fs::write(
        conf.join("DSView.conf"),
        "[UserHistory]\nshowDocuments=false\nshowDriverHint=false\n",
    )?;
    // Short path: sockaddr_un holds 107 bytes.
    let socket = PathBuf::from(format!("/tmp/dsview-ab-{tag}.sock"));
    let _ = std::fs::remove_file(&socket);

    let mut cmd = Command::new(bin);
    cmd.env_remove("DSVIEW_IMPL");
    for sub in SUBSYSTEMS {
        cmd.env_remove(format!("DSVIEW_IMPL_{sub}"));
    }
    if let Some(iml) = iml {
        cmd.env("DSVIEW_IMPL", iml);
    }
    let child = cmd
        .arg("--mcp")
        // same set iteration order in both runs' decoders
        .env("PYTHONHASHSEED", "0")
        .env("DSVIEW_MCP_SOCKET", &socket)
        .env("QT_QPA_PLATFORM", "offscreen")
        .env_remove("QT_QPA_PLATFORMTHEME")
        .env_remove("DISPLAY")
        .env_remove("WAYLAND_DISPLAY")
        .env("HOME", &home)
        .env("XDG_CONFIG_HOME", home.join(".config"))
        .env("XDG_DATA_HOME", home.join(".local/share"))
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .with_context(|| format!("starting {}", bin.display()))?;
    let inst = Instance {
        child,
        socket,
        home,
    };

    let deadline = Instant::now() + Duration::from_secs(30);
    let mut client = Client::new(&inst.socket);
    while Instant::now() < deadline {
        if let Ok(Ok(v)) = client.call("version", &json!({}), Duration::from_secs(2)) {
            // every migrated subsystem must run the requested implementation
            let imps = v["implementations"]
                .as_object()
                .cloned()
                .unwrap_or_default();
            if imps.len() != SUBSYSTEMS.len() || imps.values().any(|x| x != expect) {
                bail!("DSView (DSVIEW_IMPL={iml:?}) reports implementations {imps:?}");
            }
            return Ok(inst);
        }
        std::thread::sleep(Duration::from_millis(250));
    }
    bail!("DSView ({iml:?}) did not open its control socket");
}

fn call(c: &mut Client, method: &str, params: Value) -> Value {
    match c.call(method, &params, Duration::from_secs(120)) {
        Ok(Ok(v)) => json!({"ok": v}),
        Ok(Err(e)) => json!({"err": e}),
        Err(e) => json!({"transport": e.to_string()}),
    }
}

/// Exported file text with the wall-clock lines masked.
fn export_text(c: &mut Client, path: &Path) -> Value {
    let r = call(c, "export_data", json!({"path": path}));
    if r.get("ok").is_none() {
        return r;
    }
    let text = std::fs::read_to_string(path).unwrap_or_default();
    let _ = std::fs::remove_file(path);
    let masked: Vec<String> = text
        .lines()
        .map(|l| {
            if l.starts_with("; CSV, generated by DSView, sampled on ") {
                "; CSV, generated by DSView, sampled on <time>".to_string()
            } else if l.starts_with("$date ") {
                "$date <time> $end".to_string()
            } else {
                l.to_string()
            }
        })
        .collect();
    json!({"lines": masked.len(), "text": masked.join("\n")})
}

/// What DSView reports after opening each corpus file, and what it exports.
fn probe(socket: &Path, root: &Path, corpus: &Corpus, tag: &str) -> Value {
    let mut c = Client::new(socket);
    let mut out = serde_json::Map::new();
    for e in &corpus.files {
        let path = root.join(&e.path);
        let mut r = serde_json::Map::new();
        r.insert(
            "open_file".into(),
            call(&mut c, "open_file", json!({"path": path})),
        );
        r.insert(
            "capture_info".into(),
            call(&mut c, "capture_info", json!({})),
        );
        let base =
            std::env::temp_dir().join(format!("dsview-ab-export-{}-{tag}", std::process::id()));
        r.insert(
            "export_csv".into(),
            export_text(&mut c, &base.with_extension("csv")),
        );
        if e.mode == "logic" {
            r.insert(
                "export_vcd".into(),
                export_text(&mut c, &base.with_extension("vcd")),
            );
        }
        // Save, then describe the saved file with the Rust reader.
        let saved = base.with_extension("dsl");
        let res = call(&mut c, "save_session", json!({"path": saved}));
        let summary = if res.get("ok").is_some() && saved.exists() {
            let s = dsview_testkit::dsl_summary::summary(&saved);
            if std::env::var_os("DSVIEW_AB_KEEP").is_some() {
                let keep =
                    std::env::temp_dir().join(format!("dsview-ab-saved-{tag}-{}.dsl", out.len()));
                let _ = std::fs::copy(&saved, keep);
            }
            let _ = std::fs::remove_file(&saved);
            s
        } else {
            res
        };
        r.insert("saved".into(), summary);
        match e.mode.as_str() {
            "logic" => {
                r.insert(
                    "read_logic".into(),
                    call(&mut c, "read_logic", json!({"max_transitions": 200})),
                );
                r.insert(
                    "get_edges".into(),
                    call(&mut c, "get_edges", json!({"channel": 0, "limit": 50})),
                );
                // decode to the end, then every annotation of every stack
                r.insert(
                    "run_decoders".into(),
                    call(&mut c, "run_decoders", json!({})),
                );
                let decoders = call(&mut c, "list_active_decoders", json!({}));
                let n = decoders["ok"]["decoders"].as_array().map_or(0, Vec::len);
                r.insert("list_active_decoders".into(), decoders);
                for d in 0..n {
                    let mut all = Vec::new();
                    loop {
                        let page = call(
                            &mut c,
                            "get_annotations",
                            json!({"decoder": d, "offset": all.len(), "limit": 2000}),
                        );
                        let got: Vec<Value> = page["ok"]["annotations"]
                            .as_array()
                            .cloned()
                            .unwrap_or_default();
                        let more = got.len() == 2000;
                        all.extend(got);
                        if !more {
                            if page.get("ok").is_none() {
                                all.push(page);
                            }
                            break;
                        }
                    }
                    // Rows that start on the same sample come in decoder load
                    // order, which for the C engine is the directory order of
                    // the file system (DEVIATIONS F25): compare them as a set.
                    all.sort_by_cached_key(|a| (a["start_sample"].as_u64(), a.to_string()));
                    r.insert(format!("annotations_{d}"), Value::Array(all));
                }
            }
            "dso" => {
                for ch in [0, 1] {
                    r.insert(
                        format!("read_waveform_{ch}"),
                        call(
                            &mut c,
                            "read_waveform",
                            json!({"channel": ch, "max_points": 64}),
                        ),
                    );
                }
            }
            _ => {}
        }
        out.insert(e.path.clone(), Value::Object(r));
    }
    Value::Object(out)
}

pub fn run(root: &Path, args: &[&str]) -> Result<()> {
    let bin = match args {
        ["--bin", b] => PathBuf::from(b),
        _ => bail!(
            "usage: cargo xtask control ab --bin <path/to/DSView built with -DDSVIEW_RUST_CORE=ON>"
        ),
    };
    let corpus = Corpus::load(root)?;
    corpus.verify(root)?;

    drop(launch(&bin, None)?);
    println!("default: every subsystem runs Rust");

    let mut results = Vec::new();
    for imp in ["c", "rust"] {
        let inst = launch(&bin, Some(imp))?;
        let r = probe(&inst.socket, root, &corpus, imp);
        drop(inst);
        results.push(r);
    }

    let mut diffs = 0;
    for e in &corpus.files {
        let (a, b) = (&results[0][&e.path], &results[1][&e.path]);
        // Both sides failing the same way is not a pass.
        let errors = a.to_string().contains("\"transport\"")
            || b.to_string().contains("\"transport\"")
            || a["open_file"].get("ok").is_none()
            || b["open_file"].get("ok").is_none()
            // Exports must contain data lines, not just a header.
            || ["export_csv", "export_vcd"]
                .iter()
                .any(|k| a.get(*k).is_some_and(|x| x["lines"].as_u64().unwrap_or(0) <= 5));
        if a == b && !errors {
            let anns: usize = (0..)
                .map_while(|d| a.get(format!("annotations_{d}")))
                .map(|v| v.as_array().map_or(0, Vec::len))
                .sum();
            println!(
                "ok   {} (reading, export{} identical with C and Rust; csv {} lines{})",
                e.path,
                if anns > 0 {
                    format!(" and {anns} annotations")
                } else {
                    String::new()
                },
                a["export_csv"]["lines"],
                a.get("export_vcd")
                    .map(|v| format!(", vcd {} lines", v["lines"]))
                    .unwrap_or_default()
            );
        } else {
            diffs += 1;
            println!(
                "FAIL {}\n  first difference: {}\n  c:    {}\n  rust: {}",
                e.path,
                first_diff(a, b, ""),
                truncate(a),
                truncate(b)
            );
        }
    }
    if diffs > 0 {
        bail!("{diffs} capture(s) differ between DSVIEW_IMPL=c and rust");
    }
    Ok(())
}

/// Where `a` and `b` first differ, as a path with both values there.
fn first_diff(a: &Value, b: &Value, path: &str) -> String {
    match (a, b) {
        (Value::Object(x), Value::Object(y)) => {
            let mut keys: Vec<&String> = x.keys().chain(y.keys()).collect();
            keys.sort();
            keys.dedup();
            keys.into_iter()
                .find(|k| x.get(*k) != y.get(*k))
                .map(|k| {
                    let (u, v) = (
                        &x.get(k).cloned().unwrap_or(Value::Null),
                        &y.get(k).cloned().unwrap_or(Value::Null),
                    );
                    first_diff(u, v, &format!("{path}.{k}"))
                })
                .unwrap_or_default()
        }
        (Value::Array(x), Value::Array(y)) => {
            match (0..x.len().max(y.len())).find(|&i| x.get(i) != y.get(i)) {
                Some(i) if i < x.len() && i < y.len() => {
                    first_diff(&x[i], &y[i], &format!("{path}[{i}]"))
                }
                Some(i) => format!("{path}: lengths {} and {} (from [{i}])", x.len(), y.len()),
                None => String::new(),
            }
        }
        _ => format!("{path}: c {} / rust {}", truncate(a), truncate(b)),
    }
}

fn truncate(v: &Value) -> String {
    let s = v.to_string();
    if s.chars().count() > 600 {
        format!("{}…", s.chars().take(600).collect::<String>())
    } else {
        s
    }
}
