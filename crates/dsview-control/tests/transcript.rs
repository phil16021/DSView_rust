//! The control API conformance transcript (testdata/control/demo-scenario.json,
//! recorded against DSView's Qt GUI) against the Rust session behind a real
//! control socket: the demo devices, the repository's decoders, no USB.

use std::path::PathBuf;
use std::sync::Arc;

use dsview_control::api::Api;
use dsview_control::server::Server;
use dsview_session::{Paths, Session};
use dsview_testkit::control::{Client, Recorded, compare, demo_scenario, run_scenario};
use dsview_usb::{Info, Open, UsbBackend, UsbDevice, UsbError};

/// A bus without devices.
struct NoUsb;

impl UsbBackend for NoUsb {
    fn list(&self) -> Result<Vec<Info>, UsbError> {
        Ok(Vec::new())
    }
    fn open(&self, _: u8, _: u8, _: Open) -> Result<Box<dyn UsbDevice>, UsbError> {
        Err(UsbError::NotFound)
    }
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn init_decoders() {
    static INIT: std::sync::Once = std::sync::Once::new();
    INIT.call_once(|| {
        dsview_decode::init(&[root().join("assets/decoders").as_path()]).expect("decoders");
        dsview_decode::load_all();
    });
}

/// Sessions share the drivers' global state: one at a time.
fn serial() -> std::sync::MutexGuard<'static, ()> {
    static LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());
    LOCK.lock().unwrap_or_else(|e| e.into_inner())
}

#[test]
fn a_dialog_blocks_mutating_methods() {
    use dsview_control::ControlBackend;
    use dsview_control::api::ViewHooks;
    struct Dialog;
    impl ViewHooks for Dialog {
        fn dialog_open(&self) -> Option<String> {
            Some("Device Options".into())
        }
    }
    let _g = serial();
    init_decoders();
    let session = Session::new(
        Paths {
            data_dir: root().join("assets"),
            profile_dir: None,
            version: "test".into(),
        },
        Arc::new(NoUsb),
    );
    session.set_default_device();
    let api = Api::with_view(session.clone(), "test", Box::new(Dialog));
    let p = serde_json::Map::new();
    let e = api.call("set_mode", &p).unwrap_err();
    assert!(
        e.starts_with("DSView is showing a dialog (Device Options)"),
        "{e}"
    );
    assert!(api.call("get_config", &p).is_ok());
    assert_eq!(api.call("nope", &p).unwrap_err(), "unknown method: nope");
    session.exit();
}

#[test]
fn demo_transcript_matches_qt() {
    let _g = serial();
    let root = root();
    init_decoders();
    let session = Session::new(
        Paths {
            data_dir: root.join("assets"),
            profile_dir: None,
            version: "test".into(),
        },
        Arc::new(NoUsb),
    );
    session.set_default_device();

    let dir = std::env::temp_dir().join(format!("dsvctl-t-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let sock = dir.join("s.sock");
    let server = Server::start(&sock, Arc::new(Api::new(session.clone(), "test"))).unwrap();
    let mut client = Client::new(&sock);
    let out = dir.join("out");
    std::fs::create_dir_all(&out).unwrap();
    let actual = run_scenario(&mut client, &demo_scenario(), &out).expect("scenario");

    // what the saved file holds: the capture and the four demo decoders
    let mut r = dsview_formats::dsl::DslReader::open(&out.join("transcript.dsl")).unwrap();
    assert_eq!(r.header().total_samples, 131072);
    assert_eq!(r.decoder_stacks().unwrap().len(), 4);
    let csv = std::fs::read_to_string(out.join("transcript.csv")).unwrap();
    assert!(
        csv.starts_with("; CSV, generated by DSView"),
        "{}",
        &csv[..80.min(csv.len())]
    );

    drop(server);
    session.exit();
    let _ = std::fs::remove_dir_all(&dir);

    let stored: Vec<Recorded> = serde_json::from_str(
        &std::fs::read_to_string(root.join("testdata/control/demo-scenario.json")).unwrap(),
    )
    .unwrap();
    let problems = compare(&stored, &actual);
    assert!(problems.is_empty(), "{}", problems.join("\n"));
}

/// DSO voltages are in the V/div of the capture, as `get_voltage`: a V/div
/// changed afterwards only stretches the trace.
#[test]
fn dso_voltages_keep_the_capture_vdiv() {
    use dsview_control::ControlBackend;
    let _g = serial();
    init_decoders();
    let session = Session::new(
        Paths {
            data_dir: root().join("assets"),
            profile_dir: None,
            version: "test".into(),
        },
        Arc::new(NoUsb),
    );
    session.set_default_device();
    let api = Api::new(session.clone(), "test");
    let call = |m: &str, p: serde_json::Value| {
        api.call(m, p.as_object().unwrap())
            .unwrap_or_else(|e| panic!("{m}: {e}"))
    };
    call("set_mode", serde_json::json!({"mode": "dso"}));
    call("start_capture", serde_json::json!({"timeout_s": 30}));
    let before = call("measure_dso", serde_json::json!({"channel": 0}));
    let vdiv = |cfg: &serde_json::Value| cfg["channels"][0]["vdiv_mv"].as_u64().unwrap();
    let v0 = vdiv(&call("get_config", serde_json::json!({})));
    let cfg = call(
        "set_dso",
        serde_json::json!({"channel": 0, "vdiv_mv": v0 * 2}),
    );
    assert_ne!(vdiv(&cfg), v0, "{cfg}");
    let after = call("measure_dso", serde_json::json!({"channel": 0}));
    assert_eq!(before, after);
    session.exit();
}

/// F31: a V/div changed while a capture runs applies to the frames that
/// follow, which are in the new V/div: the signal's voltages stay.
#[test]
fn dso_vdiv_changed_while_running() {
    use dsview_control::ControlBackend;
    let _g = serial();
    init_decoders();
    let session = Session::new(
        Paths {
            data_dir: root().join("assets"),
            profile_dir: None,
            version: "test".into(),
        },
        Arc::new(NoUsb),
    );
    session.set_default_device();
    let api = Api::new(session.clone(), "test");
    let call = |m: &str, p: serde_json::Value| {
        api.call(m, p.as_object().unwrap())
            .unwrap_or_else(|e| panic!("{m}: {e}"))
    };
    // the peak-to-peak voltage of channel 0, in mV
    let vpp = || -> f64 {
        let m = call("measure_dso", serde_json::json!({"channel": 0}));
        let v = m["measurements"]["peak_to_peak"]
            .as_str()
            .unwrap_or_else(|| panic!("no peak_to_peak in {m}"))
            .to_owned();
        let (num, unit) = v.split_at(v.find(|c: char| c.is_ascii_alphabetic()).unwrap());
        num.parse::<f64>().unwrap() * if unit.starts_with("mV") { 1.0 } else { 1000.0 }
    };
    let frames = || session.state().dso_seq;
    let wait_frames = |n: u64| {
        let from = frames();
        let t0 = std::time::Instant::now();
        while frames() < from + n {
            assert!(
                t0.elapsed() < std::time::Duration::from_secs(30),
                "no DSO frames"
            );
            std::thread::sleep(std::time::Duration::from_millis(20));
        }
    };
    call("set_mode", serde_json::json!({"mode": "dso"}));
    call(
        "start_capture",
        serde_json::json!({"instant": false, "wait": false}),
    );
    wait_frames(3);
    let before = vpp();
    // the GUI's V/div dial while running (the API refuses set_dso then)
    let pos = session
        .channels()
        .iter()
        .position(|c| c.index == 0 && c.ty == dsview_core::channel_type::DSO)
        .unwrap();
    let v0 = session.channels()[pos].vdiv;
    assert!(session.set_config(
        dsview_core::key::PROBE_VDIV,
        dsview_core::ConfValue::U64(v0 * 2),
        Some(pos)
    ));
    assert_eq!(session.channels()[pos].vdiv, v0 * 2);
    wait_frames(3);
    let after = vpp();
    call("stop_capture", serde_json::json!({}));
    assert!(
        (after / before - 1.0).abs() < 0.2,
        "Vpp {before} mV before, {after} mV after the V/div change"
    );
    session.exit();
}
