#!/usr/bin/env python3
"""Generates crates/dsview-drivers/src/dsl/tables.rs from libsigrok4DSL's
hardware/DSL/dsl.h and dslogic.c (profiles, channel modes, rate and range
lists, option lists). Run from the repository root:
    python3 tools/gen/dsl_tables.py > crates/dsview-drivers/src/dsl/tables.rs
"""
import re, sys

ROOT = '.'
dsl_h = open(f'{ROOT}/libsigrok4DSL/hardware/DSL/dsl.h').read()
sig_h = open(f'{ROOT}/libsigrok4DSL/libsigrok.h').read()
dslogic_c = open(f'{ROOT}/libsigrok4DSL/hardware/DSL/dslogic.c').read()

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)

dsl_h = strip_comments(dsl_h)
sig_h = strip_comments(sig_h)
dslogic_c = strip_comments(dslogic_c)

consts = {}
def add_enum(src, name):
    m = re.search(r'enum\s+' + name + r'\s*\{(.*?)\}', src, re.S)
    nxt = 0
    for part in m.group(1).split(','):
        part = part.strip()
        if not part:
            continue
        if '=' in part:
            k, v = [x.strip() for x in part.split('=')]
            nxt = int(v, 0)
        else:
            k = part
        consts[k] = nxt
        nxt += 1

add_enum(sig_h, 'DSL_CHANNEL_ID')
add_enum(sig_h, 'OPERATION_MODE')
add_enum(sig_h, 'CHANNEL_TYPE')
for k, v in re.findall(r'#define\s+(CAPS_\w+)\s+\(1\s*<<\s*(\d+)\)', dsl_h):
    consts[k] = 1 << int(v)
consts.update({'CAPS_FEATURE_NONE': 0, 'TRUE': 1, 'FALSE': 0, 'NULL': None,
               'DS_VENDOR_ID': 0x2A0E, 'DSL_VGA_ID_E8': 0xE8,
               'LIBUSB_SPEED_UNKNOWN': 0, 'LIBUSB_SPEED_LOW': 1, 'LIBUSB_SPEED_FULL': 2,
               'LIBUSB_SPEED_HIGH': 3, 'LIBUSB_SPEED_SUPER': 4})
for k, v in re.findall(r'#define\s+(DSL_E8_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b', dsl_h):
    consts[k] = int(v, 0)

UNITS = {'SR_HZ': 1, 'SR_KHZ': 1000, 'SR_MHZ': 10**6, 'SR_GHZ': 10**9, 'SR_Kn': 1000,
         'SR_Mn': 10**6, 'SR_KB': 1024, 'SR_MB': 1 << 20, 'SR_GB': 1 << 30, 'SR_B': 1, 'SR_mV': 1, 'SR_V': 1000,
         'SR_NS': 1, 'SR_US': 1000, 'SR_MS': 10**6, 'SR_SEC': 10**9}

arrays = {}  # C array name -> Rust const name

def value(expr):
    """A C initializer expression: int, string, None or ('array', name)."""
    e = expr.strip()
    if e.startswith('"'):
        return e
    if e in arrays:
        return ('array', arrays[e])
    if e == 'NULL' or e == '0' and False:
        return None
    py = e
    for u, f in UNITS.items():
        py = re.sub(r'\b' + u + r'\(([^()]*)\)', lambda m: f'(({m.group(1)})*{f})', py)
    py = re.sub(r'\b([A-Za-z_]\w*)\b', lambda m: repr(consts[m.group(1)]) if m.group(1) in consts else m.group(1), py)
    py = py.replace('ULL', '').replace('/', '//').strip()
    # a commented-out last term leaves a dangling '|'
    py = py.rstrip('|').strip()
    return int(eval('(' + ' '.join(py.split()) + ')'))

def split_top(s):
    parts, depth, cur, instr = [], 0, '', False
    for ch in s:
        if ch == '"':
            instr = not instr
        if not instr:
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
            elif ch == ',' and depth == 0:
                parts.append(cur); cur = ''; continue
        cur += ch
    if cur.strip():
        parts.append(cur)
    return [p.strip() for p in parts]

def body_of(src, decl):
    i = src.index(decl)
    i = src.index('{', i)
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '{': depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0:
                return src[i + 1:j]

out = []
w = out.append
w('// Generated by tools/gen/dsl_tables.py from libsigrok4DSL/hardware/DSL/dsl.h')
w('// and dslogic.c; do not edit.')
w('')
w('#![allow(clippy::unreadable_literal, non_upper_case_globals)]')
w('')
w('use super::{Caps, ChannelMode, Profile};')
w('use crate::dsl::Speed;')
w('use dsview_core::{Mode, ListItem};')
w('')
# channel id constants
w('/// `enum DSL_CHANNEL_ID`')
w('pub mod ch {')
for k, v in sorted(((k, v) for k, v in consts.items() if k.startswith('DSL_') and k[4:5].isupper() and isinstance(v, int) and re.match(r'DSL_(STREAM|BUFFER|ANALOG|DSO)', k)), key=lambda x: x[1]):
    w(f'    pub const {k}: u16 = {v};')
w('}')
w('')

# rate/range arrays
for name in ['vdivs10to2000', 'samplerates100', 'samplerates400', 'vdivs_dso_e8', 'samplerates_dso_e8',
             'samplerates_logic_e8', 'samplerates1000']:
    m = re.search(r'static const uint64_t ' + name + r'\[\]\s*=\s*\{(.*?)\};', dsl_h, re.S)
    if not m:
        continue
    vals = [value(x) for x in split_top(m.group(1))]
    vals = [v for v in vals if v]  # 0 terminator
    rname = name.upper()
    arrays[name] = rname
    w(f'pub static {rname}: [u64; {len(vals)}] = [{", ".join(str(v) for v in vals)}];')
w('')

# channel modes
body = body_of(dsl_h, 'static const struct DSL_channels channel_modes[]')
w('/// `channel_modes[]`, indexed by channel mode id.')
modes = []
for ent in split_top(body):
    f = split_top(ent.strip()[1:-1])
    modes.append(f)
w(f'pub static CHANNEL_MODES: [ChannelMode; {len(modes)}] = [')
for f in modes:
    id_, mode, ty, stream, num, vld, ub, mn, mx, hmn, hmx, pre, descr = f
    mode_rs = {0: 'Mode::Logic', 1: 'Mode::Dso', 2: 'Mode::Analog'}[value(mode)]
    w(f'    ChannelMode {{ id: {value(id_)}, mode: {mode_rs}, ty: {value(ty)}, stream: {str(bool(value(stream))).lower()}, '
      f'num: {value(num)}, vld_num: {value(vld)}, unit_bits: {value(ub)}, min_samplerate: {value(mn)}, '
      f'max_samplerate: {value(mx)}, hw_min_samplerate: {value(hmn)}, hw_max_samplerate: {value(hmx)}, '
      f'pre_div: {value(pre)}, descr: {descr} }},')
w('];')
w('')

def profiles(decl, rname):
    body = body_of(dsl_h, decl)
    ents = [e for e in split_top(body) if e.strip()]
    rows = []
    for ent in ents:
        f = split_top(ent.strip()[1:-1])
        if value(f[0]) == 0:
            continue
        vid, pid, speed, vendor, model, mver, fw, b33, b50, caps = f
        c = split_top(caps.strip()[1:-1])
        names = ['mode_caps', 'feature_caps', 'channels', 'total_ch_num', 'hw_depth', 'dso_depth',
                 'intest_channel', 'vdivs', 'samplerates', 'vga_id', 'default_channelmode',
                 'default_samplerate', 'default_samplelimit', 'default_pwmtrans', 'default_pwmmargin',
                 'ref_min', 'ref_max', 'default_comb_comp', 'half_samplerate', 'quarter_samplerate']
        assert len(c) == len(names), (pid, len(c))
        cv = {}
        for n, x in zip(names, c):
            v = value(x)
            if n in ('vdivs', 'samplerates'):
                cv[n] = f'&{v[1]}' if isinstance(v, tuple) else '&[]'
            else:
                cv[n] = str(v)
        spd = {0: 'Unknown', 1: 'Low', 2: 'Full', 3: 'High', 4: 'Super'}[value(speed)]
        opt = lambda s: 'None' if value(s) is None else f'Some({s})'
        caps_rs = ', '.join(f'{n}: {cv[n]}' for n in names)
        rows.append(f'    Profile {{ vid: {value(vid):#06x}, pid: {value(pid):#06x}, speed: Speed::{spd}, vendor: {vendor}, '
                    f'model: {model}, model_version: {opt(mver)}, firmware: {opt(fw)}, fpga_bit33: {opt(b33)}, '
                    f'fpga_bit50: {opt(b50)}, caps: Caps {{ {caps_rs} }} }},')
    w(f'pub static {rname}: [Profile; {len(rows)}] = [')
    out.extend(rows)
    w('];')
    w('')

profiles('static const struct DSL_profile supported_DSLogic[]', 'DSLOGIC_PROFILES')
profiles('static const struct DSL_profile supported_DSCope[]', 'DSCOPE_PROFILES')

# dslogic.c lists
consts.update({'LO_OP_BUFFER': 0, 'LO_OP_STREAM': 1, 'LO_OP_INTEST': 2, 'SR_BUF_STOP': 0, 'SR_BUF_UPLOAD': 1,
               'SR_TH_3V3': 0, 'SR_TH_5V0': 1, 'SR_FILTER_NONE': 0, 'SR_FILTER_1T': 1})
for name, rname in [('opmode_list', 'OPMODE_LIST'), ('bufoption_list', 'BUFOPTION_LIST'),
                    ('threshold_list', 'THRESHOLD_LIST'), ('filter_list', 'FILTER_LIST')]:
    body = body_of(dslogic_c, f'static const struct sr_list_item {name}[]')
    items = []
    for ent in split_top(body):
        f = split_top(ent.strip()[1:-1])
        if f[1] == 'NULL':
            continue
        items.append((value(f[0]), f[1]))
    w(f'pub fn {name}() -> Vec<ListItem> {{')
    w('    vec![' + ', '.join(f'ListItem {{ id: {i}, name: {n}.into() }}' for i, n in items) + ']')
    w('}')
    w('')

for name, rname in [('hwoptions', 'HWOPTIONS'), ('hwoptions_pro', 'HWOPTIONS_PRO'),
                    ('sessions', 'SESSIONS'), ('sessions_pro', 'SESSIONS_PRO')]:
    body = body_of(dslogic_c, f'static const int32_t {name}[]')
    keys = [x.strip() for x in split_top(body)]
    w(f'pub static {rname}: [i32; {len(keys)}] = [' + ', '.join('dsview_core::key::' + k.replace('SR_CONF_', '') for k in keys) + '];')
w('')
print('\n'.join(out))
